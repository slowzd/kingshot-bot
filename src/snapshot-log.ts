import fs from "node:fs";
import path from "node:path";
import type { PowerSnapshot } from "./mightpulse.ts";
import { postTime } from "./time.ts";

const HEADER = "// Generated by the hourly leaderboard job. Do not edit by hand.\nexport const snapshotLog = ";
const HISTORY_LIMIT = 24 * 7 * 2;

export interface SnapshotUse {
  /** Leaderboard update this snapshot was used for (XX:01 UTC). */
  update: string;
  /** When the job fetched the API. */
  fetchedAt: string;
  /** When Mightpulse captured the rankings. */
  apiCapturedAt: string;
  apiAgeMinutes: number;
}

export interface SnapshotLog {
  kingdom: number;
  latest: SnapshotUse & {
    alliances: { rank: number; id: number; tag: string; name: string; power: number }[];
  };
  /** Newest first. */
  history: SnapshotUse[];
}

export function snapshotUse(snapshot: PowerSnapshot, hour: Date, fetchedAt: Date): SnapshotUse {
  return {
    update: postTime(hour).toISOString(),
    fetchedAt: fetchedAt.toISOString(),
    apiCapturedAt: snapshot.capturedAt.toISOString(),
    apiAgeMinutes: Math.max(0, Math.round((fetchedAt.getTime() - snapshot.capturedAt.getTime()) / 60_000)),
  };
}

export function loadSnapshotLog(file: string): SnapshotLog | null {
  let contents: string;
  try {
    contents = fs.readFileSync(file, "utf8");
  } catch (error) {
    if (error instanceof Error && "code" in error && error.code === "ENOENT") return null;
    throw error;
  }
  if (!contents.startsWith(HEADER)) throw new Error(`${file} is not a generated snapshot log.`);
  const log = JSON.parse(contents.slice(HEADER.length).trim().replace(/;$/, "")) as SnapshotLog;
  if (!Array.isArray(log.history)) throw new Error(`${file} has no snapshot history.`);
  return log;
}

export function recordSnapshot(file: string, snapshot: PowerSnapshot, hour: Date, fetchedAt: Date): SnapshotUse {
  const use = snapshotUse(snapshot, hour, fetchedAt);
  const previous = loadSnapshotLog(file);
  const history = previous?.kingdom === snapshot.kingdom ? previous.history : [];
  const log: SnapshotLog = {
    kingdom: snapshot.kingdom,
    latest: {
      ...use,
      alliances: snapshot.alliances.map(({ rank, id, tag, name, power }) => ({ rank, id, tag, name, power })),
    },
    history: [use, ...history].slice(0, HISTORY_LIMIT),
  };
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const temporary = `${file}.${process.pid}.tmp`;
  fs.writeFileSync(temporary, `${HEADER}${JSON.stringify(log, null, 2)};\n`);
  fs.renameSync(temporary, file);
  return use;
}
